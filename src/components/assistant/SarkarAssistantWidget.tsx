import React, { useMemo, useState } from 'react';
import {
  Bot,
  Send,
  X,
  AlertCircle,
  FileText,
  HelpCircle,
  CheckCircle2,
  ArrowRight,
  Minimize2,
} from 'lucide-react';
import { useNavigate } from 'react-router-dom';
import { useApp } from '../../context/AppContext';
import { DocumentRecord } from '../../types';

interface ChatMessage {
  id: string;
  sender: 'assistant' | 'officer';
  text: string;
  timestamp: string;
}

function generateContextualReply(
  query: string,
  doc: DocumentRecord | undefined,
  backendMode: 'demo' | 'fastapi'
): string {
  const q = query.toLowerCase();

  if (!doc) {
    return 'Select any document record to inspect field explanations, missing entries, or low-confidence OCR scores.';
  }

  const missingFields = doc.fields.filter((f) => !f.value || f.value.trim() === '');
  const lowFields = doc.fields.filter((f) => f.confidence < 70);
  const medFields = doc.fields.filter((f) => f.confidence >= 70 && f.confidence < 85);

  if (q.includes('missing') || q.includes('blank') || q.includes('empty')) {
    if (missingFields.length === 0) {
      return `All ${doc.fields.length} extracted fields in ${doc.applicationNumber} (${doc.formType}) contain values. No blank mandatory fields were detected.`;
    }
    return `Detected ${missingFields.length} missing field(s) in ${doc.applicationNumber}: ${missingFields
      .map((f) => `${f.label}${f.ocrNote ? ` (${f.ocrNote})` : ''}`)
      .join('; ')}. Recommend checking the physical scan or requesting applicant clarification before verification.`;
  }

  if (q.includes('low') || q.includes('confidence') || q.includes('score') || q.includes('error')) {
    if (lowFields.length === 0 && medFields.length === 0) {
      return `Every field in ${doc.applicationNumber} scored High confidence (85%+), with an overall reliability of ${doc.overallConfidence}%.`;
    }
    const items = [...lowFields, ...medFields].map(
      (f) =>
        `• ${f.label}: ${f.confidence}% (${f.ocrNote || 'Handwritten stroke variation or background grid overlap detected'})`
    );
    return `Confidence breakdown for ${doc.applicationNumber} (${doc.overallConfidence}% overall):\n${items.join(
      '\n'
    )}\nVerify these highlighted fields against the left-pane document scan before clicking Verify & Save Record.`;
  }

  if (q.includes('explain') || q.includes('summary') || q.includes('field')) {
    const coreSummary = doc.fields
      .slice(0, 5)
      .map((f) => `• ${f.label}: ${f.value || '[Missing]'} (${f.confidence}%)`)
      .join('\n');
    return `Document ${doc.applicationNumber} belongs to ${doc.departmentName} (${doc.formType}, ${doc.language}). Key extracted values:\n${coreSummary}\nStatus: ${doc.status}.`;
  }

  if (
    q.includes('form') ||
    q.includes('rule') ||
    q.includes('pahani') ||
    q.includes('parihara') ||
    q.includes('kannada') ||
    q.includes('document')
  ) {
    if (doc.departmentId === 'revenue') {
      return `For Revenue Department "${doc.formType}", verify Survey Number format (e.g., 14/2A), Land Extent (Acres/Guntas), and ensure the Inheritance/Sale Mutation Reason matches the Taluk stamp date.`;
    }
    if (doc.departmentId === 'agriculture') {
      return `For Agriculture "${doc.formType}", Parihara claims require Farmer Name, Survey/Hissa Number, Crop Loss %, and complete Section 6 Bank Account/IFSC details before treasury disbursement.`;
    }
    if (doc.departmentId === 'panchayat') {
      return `For Panchayat Raj "${doc.formType}", verify the Ward/Village name, Plot & Khata numbers, and Sarpanch/PDO seal at the bottom margin before syncing to E-Swathu.`;
    }
    return `For ${doc.departmentName} (${doc.formType}), confirm Applicant Name, Father's Name, Village/District spelling in ${doc.language}, and Application Number (${doc.applicationNumber}) prior to archival.`;
  }

  const modeNote =
    backendMode === 'demo'
      ? ' (Generated by Local Demo RAG Assistant)'
      : ' (FastAPI RAG endpoint standby fallback)';

  return `Inspecting ${doc.applicationNumber} (${doc.departmentName}): ${
    missingFields.length
  } missing field(s) and ${lowFields.length} low-confidence field(s) below 70%. Ask me to "explain fields", "find missing info", or "explain low confidence" for detailed diagnostics.${modeNote}`;
}

interface SarkarAssistantPanelProps {
  embedded?: boolean;
}

export const SarkarAssistantPanel: React.FC<SarkarAssistantPanelProps> = ({
  embedded = false,
}) => {
  const navigate = useNavigate();
  const {
    documents,
    assistantDocId,
    setAssistantDocId,
    backendMode,
    setAssistantOpen,
  } = useApp();

  const activeDoc = useMemo(
    () => documents.find((d) => d.id === assistantDocId) || documents[0],
    [documents, assistantDocId]
  );

  const [input, setInput] = useState('');
  const [messages, setMessages] = useState<ChatMessage[]>([
    {
      id: 'welcome-msg',
      sender: 'assistant',
      text: 'Namaskara. I am SARKAR AI Assistant. I inspect Kannada & English OCR outputs, flag missing entries, explain low-confidence scores, and guide department verification rules.',
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    },
  ]);

  const sendQuery = (text: string) => {
    const trimmed = text.trim();
    if (!trimmed) return;

    const nowTime = new Date().toLocaleTimeString([], {
      hour: '2-digit',
      minute: '2-digit',
    });

    const userMsg: ChatMessage = {
      id: `u-${Date.now()}`,
      sender: 'officer',
      text: trimmed,
      timestamp: nowTime,
    };

    const replyText = generateContextualReply(trimmed, activeDoc, backendMode);
    const botMsg: ChatMessage = {
      id: `a-${Date.now() + 1}`,
      sender: 'assistant',
      text: replyText,
      timestamp: nowTime,
    };

    setMessages((prev) => [...prev, userMsg, botMsg]);
    setInput('');
  };

  const missingCount =
    activeDoc?.fields.filter((f) => !f.value || f.value.trim() === '').length || 0;
  const lowCount = activeDoc?.fields.filter((f) => f.confidence < 70).length || 0;

  return (
    <div
      className={`flex flex-col bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 ${
        embedded
          ? 'rounded-lg h-[calc(100vh-11rem)] min-h-[540px]'
          : 'rounded-lg shadow-xl h-[560px] w-full sm:w-[410px]'
      }`}
    >
      {/* Header */}
      <div className="flex items-center justify-between gap-3 px-4 py-3 border-b border-slate-200 dark:border-slate-800 bg-[#0F294A] text-white rounded-t-lg">
        <div className="flex items-center gap-2.5 min-w-0">
          <div className="w-8 h-8 rounded-md bg-white/10 flex items-center justify-center shrink-0">
            <Bot className="w-4 h-4 text-amber-300" />
          </div>
          <div className="min-w-0">
            <h3 className="text-sm font-semibold truncate">SARKAR AI Assistant</h3>
            <p className="text-[11px] text-slate-300 truncate">
              {backendMode === 'demo'
                ? 'Demo RAG Mode · Local Rules Engine'
                : 'Connected to FastAPI RAG'}
            </p>
          </div>
        </div>
        {!embedded && (
          <button
            type="button"
            onClick={() => setAssistantOpen(false)}
            aria-label="Close SARKAR AI Assistant"
            className="p-1.5 rounded-md text-slate-300 hover:text-white hover:bg-white/10 transition-colors"
          >
            <Minimize2 className="w-4 h-4" />
          </button>
        )}
      </div>

      {/* Active Document Selector */}
      <div className="px-4 py-2.5 border-b border-slate-200 dark:border-slate-800 bg-slate-50 dark:bg-slate-950/60 flex flex-col gap-2">
        <div className="flex items-center justify-between gap-2">
          <label
            htmlFor="assistant-doc-select"
            className="text-xs font-medium text-slate-600 dark:text-slate-400 whitespace-nowrap"
          >
            Active Record:
          </label>
          <select
            id="assistant-doc-select"
            value={activeDoc?.id || ''}
            onChange={(e) => setAssistantDocId(e.target.value)}
            className="flex-1 min-w-0 text-xs font-mono bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-md px-2 py-1.5 text-slate-800 dark:text-slate-200 focus:outline-none focus:ring-2 focus:ring-blue-700"
          >
            {documents.map((d) => (
              <option key={d.id} value={d.id}>
                {d.applicationNumber} · {d.departmentName.replace(' Department', '')}
              </option>
            ))}
          </select>
        </div>

        {activeDoc && (
          <div className="flex items-center justify-between gap-2 text-xs text-slate-600 dark:text-slate-400">
            <div className="flex items-center gap-3 tabular-nums">
              <span className="inline-flex items-center gap-1">
                <AlertCircle className="w-3.5 h-3.5 text-amber-600 dark:text-amber-400" />
                {missingCount} missing
              </span>
              <span aria-hidden="true">·</span>
              <span className="inline-flex items-center gap-1">
                <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600 dark:text-emerald-400" />
                {lowCount} low conf
              </span>
            </div>
            <button
              type="button"
              onClick={() => {
                navigate(`/documents/${activeDoc.id}`);
                if (!embedded) setAssistantOpen(false);
              }}
              className="inline-flex items-center gap-1 text-xs font-medium text-[#1E3A8A] dark:text-blue-400 hover:underline whitespace-nowrap shrink-0"
            >
              Open Review <ArrowRight className="w-3 h-3" />
            </button>
          </div>
        )}
      </div>

      {/* Messages */}
      <div className="flex-1 overflow-y-auto p-4 space-y-3">
        {messages.map((msg) => (
          <div
            key={msg.id}
            className={`flex flex-col ${
              msg.sender === 'officer' ? 'items-end' : 'items-start'
            }`}
          >
            <div
              className={`max-w-[88%] rounded-lg px-3.5 py-2.5 text-xs leading-relaxed whitespace-pre-line ${
                msg.sender === 'officer'
                  ? 'bg-[#0F294A] text-white'
                  : 'bg-slate-100 dark:bg-slate-800 text-slate-800 dark:text-slate-200 border border-slate-200 dark:border-slate-700'
              }`}
            >
              {msg.text}
            </div>
            <span className="mt-1 text-[10px] font-mono tabular-nums text-slate-400">
              {msg.sender === 'officer' ? 'Officer' : 'SARKAR AI'} · {msg.timestamp}
            </span>
          </div>
        ))}
      </div>

      {/* Quick Prompts */}
      <div className="px-4 py-2 border-t border-slate-200 dark:border-slate-800 flex items-center gap-1.5 overflow-x-auto">
        <button
          type="button"
          onClick={() => sendQuery('Explain extracted fields')}
          className="inline-flex items-center gap-1 px-2.5 py-1 text-[11px] font-medium rounded-md border border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 whitespace-nowrap shrink-0"
        >
          <FileText className="w-3 h-3" /> Explain fields
        </button>
        <button
          type="button"
          onClick={() => sendQuery('Find missing information')}
          className="inline-flex items-center gap-1 px-2.5 py-1 text-[11px] font-medium rounded-md border border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 whitespace-nowrap shrink-0"
        >
          <AlertCircle className="w-3 h-3" /> Missing info
        </button>
        <button
          type="button"
          onClick={() => sendQuery('Explain low confidence scores')}
          className="inline-flex items-center gap-1 px-2.5 py-1 text-[11px] font-medium rounded-md border border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 whitespace-nowrap shrink-0"
        >
          <HelpCircle className="w-3 h-3" /> Low confidence
        </button>
      </div>

      {/* Input */}
      <form
        onSubmit={(e) => {
          e.preventDefault();
          sendQuery(input);
        }}
        className="p-3 border-t border-slate-200 dark:border-slate-800 flex items-center gap-2"
      >
        <input
          type="text"
          value={input}
          onChange={(e) => setInput(e.target.value)}
          placeholder="Ask about fields, Kannada OCR, or form rules..."
          className="flex-1 min-w-0 text-xs bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-700 rounded-md px-3 py-2 text-slate-900 dark:text-slate-100 placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-blue-700"
        />
        <button
          type="submit"
          aria-label="Send message"
          className="px-3 py-2 rounded-md bg-[#0F294A] hover:bg-[#1E3A8A] text-white transition-colors inline-flex items-center justify-center shrink-0"
        >
          <Send className="w-3.5 h-3.5" />
        </button>
      </form>
    </div>
  );
};

export const SarkarAssistantWidget: React.FC = () => {
  const { assistantOpen, setAssistantOpen } = useApp();

  return (
    <div className="fixed bottom-5 right-5 z-40 flex flex-col items-end gap-3">
      {assistantOpen && <SarkarAssistantPanel />}

      <button
        type="button"
        onClick={() => setAssistantOpen(!assistantOpen)}
        className="inline-flex items-center gap-2.5 px-4 py-2.5 rounded-lg bg-[#0F294A] hover:bg-[#1E3A8A] text-white text-sm font-medium shadow-lg border border-white/10 transition-all whitespace-nowrap shrink-0"
      >
        {assistantOpen ? (
          <>
            <X className="w-4 h-4" />
            <span>Close Assistant</span>
          </>
        ) : (
          <>
            <Bot className="w-4 h-4 text-amber-300" />
            <span>SARKAR AI Assistant</span>
          </>
        )}
      </button>
    </div>
  );
};
